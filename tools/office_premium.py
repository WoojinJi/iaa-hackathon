"""Office premium for the 20 reference policies (Part 2 task; assessed in the report, not on Kaggle).

  office premium = (risk premium + cat reinsurance + fixed expense)
                   / (1 - variable expense - channel commission - premium tax - target profit)
  cat reinsurance = cat share x risk premium, property lines (buildings, contents) only   [open question 4]

Risk premium = our submission's prediction for the row (row period). Two bases are shown because the task
leaves it open (question 2): annual (risk premium / exposure, comparable with written_premium, which is the
full annual premium) and row period (the row's risk premium with the full fixed expense).

Writes  docs/office_premium_reference.md            (committed; the table and the assumptions used)
        results/office_premium/reference_20.csv      (not committed; for the spreadsheet check)
        results/office_premium/reference_20.xlsx     (if openpyxl is installed)

Usage (repository root):
  python tools/office_premium.py --submission submissions/p2_v1.csv
"""
import argparse
from pathlib import Path

import pandas as pd

PROPERTY = {"buildings", "contents"}


def expense_table(data_dir):
    e = pd.read_parquet(Path(data_dir) / "expenses.parquet").set_index("item")
    return e["emerging"], e


def build(data_dir, submission):
    ex, full = expense_table(data_dir)
    ref = pd.read_parquet(Path(data_dir) / "reference_policies.parquet")
    sub = pd.read_csv(submission, dtype={"row_id": str})
    t = ref.merge(sub, on="row_id", how="left", validate="one_to_one")
    assert t.prediction.notna().all(), "every reference policy needs a prediction"
    comm = t.channel.map(lambda c: ex.get(f"commission_{c}"))
    if comm.isna().any():
        raise ValueError(f"no emerging commission for channel(s) {sorted(t.channel[comm.isna()].unique())} (question 1)")
    cat_share = t.line.map(lambda ln: ex["cat_reinsurance"] if ln in PROPERTY else 0.0)
    den = 1 - ex["variable_expense"] - comm - ex["premium_tax"] - ex["target_profit_margin"]
    fixed = ex["fixed_expense_per_policy"]

    out = pd.DataFrame({"row_id": t.row_id, "line": t.line, "channel": t.channel, "new_business": t.new_business,
                        "exposure": t.exposure})
    out["risk_row"] = t.prediction
    out["risk_annual"] = t.prediction / t.exposure
    out["cat_annual"] = cat_share * out.risk_annual
    out["fixed"] = fixed
    out["numerator_annual"] = out.risk_annual + out.cat_annual + fixed
    out["commission"] = comm
    out["divisor"] = den
    out["office_annual"] = out.numerator_annual / den
    out["office_row_period"] = (out.risk_row + cat_share * out.risk_row + fixed) / den
    out["current_premium"] = t.written_premium
    out["office_annual / current"] = out.office_annual / t.written_premium
    # pieces of the annual office premium (they add up to it): a check for the spreadsheet
    for item, col in [("variable_expense", "variable"), ("premium_tax", "tax"), ("target_profit_margin", "profit")]:
        out[f"{col}_annual"] = ex[item] * out.office_annual
    out["commission_annual"] = comm * out.office_annual
    check = out.numerator_annual + out[["variable_annual", "tax_annual", "profit_annual", "commission_annual"]].sum(axis=1)
    assert (check - out.office_annual).abs().max() < 1e-6
    return out, full


def markdown(out, full, submission):
    cols = ["row_id", "line", "channel", "exposure", "risk_row", "risk_annual", "cat_annual", "fixed", "divisor",
            "office_annual", "office_row_period", "current_premium", "office_annual / current"]
    t = out[cols].copy()
    t["exposure"] = t.exposure.round(4)
    for c in cols[4:]:
        if c != "exposure":
            t[c] = t[c].round(2)
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in t.itertuples(index=False))
    exp = full.reset_index()[["item", "developed", "emerging", "unit"]]
    ehead = "| item | developed | emerging | unit |\n|---|---|---|---|\n"
    ebody = "".join(f"| {r.item} | {r.developed} | {r.emerging} | {r.unit} |\n" for r in exp.itertuples(index=False))
    by = out.groupby("line")[["office_annual / current"]].median().round(2)
    return f"""# Office premium: 20 reference policies

Generated by `tools/office_premium.py` from `{submission}` (risk premium = our prediction for the row).
Checked independently in a spreadsheet: `docs/krista_office_premium_check.md`.

**Formula:** office premium = (risk premium + cat reinsurance + fixed expense) ÷ (1 − variable expense −
channel commission − premium tax − target profit). Cat reinsurance = share × risk premium, buildings and contents.
Commission, variable expense, tax and profit are shares of the final premium, so they divide rather than add.

**Two bases (open question 2):** `office_annual` uses the annual risk premium (row risk premium ÷ exposure), comparable
with `current_premium` (written_premium, the full annual premium). `office_row_period` uses the row's own risk
premium with the full fixed expense. They differ only for short rows.

## Expense assumptions (expenses.parquet)
{ehead}{ebody}
## Table
{head}{body}
Median office_annual / current premium by line: {by['office_annual / current'].to_dict()}.

## Open questions (team decision; see the question list)
1. comparison_site commission is blank for emerging (no reference policy uses that channel).
2. Annual vs row-period basis (short rows: exposure below 0.4).
3. Fixed expense per policy per line, or per customer.
4. Cat reinsurance on contents as well as buildings (applied to both here).
5. Premium tax as a share of the office premium (in the divisor, as here) or added on top.
6. Office premium against the current premium: price inadequacy or our assumptions.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--submission", required=True)
    ap.add_argument("--data", default=str(Path(__file__).resolve().parents[1] / "data_part2" / "emerging"))
    ap.add_argument("--out-md", default="docs/office_premium_reference.md")
    ap.add_argument("--out-dir", default="results/office_premium")
    a = ap.parse_args()
    out, full = build(a.data, a.submission)
    Path(a.out_md).write_text(markdown(out, full, a.submission))
    d = Path(a.out_dir)
    d.mkdir(parents=True, exist_ok=True)
    out.to_csv(d / "reference_20.csv", index=False)
    try:
        out.to_excel(d / "reference_20.xlsx", index=False)
        xl = f" and {d / 'reference_20.xlsx'}"
    except ImportError:
        xl = " (no openpyxl: pip install openpyxl for an .xlsx)"
    print(f"wrote {a.out_md}, {d / 'reference_20.csv'}{xl}")
    pd.set_option("display.width", 220)
    print(out[["row_id", "line", "channel", "exposure", "risk_row", "risk_annual", "divisor", "office_annual",
               "office_row_period", "current_premium", "office_annual / current"]].round(2).to_string(index=False))


if __name__ == "__main__":
    main()
